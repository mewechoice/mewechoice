const fs=require("node:fs"),assert=require("node:assert/strict"),ts=require("typescript");
require.extensions[".ts"]=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,"utf8"),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,f);
const {calculateVehicleProject}=require("../lib/project/vehicle/engine.ts");
const {buildProjectEngineReading}=require("../lib/project/engine.ts");
const {buildScenarioLab}=require("../lib/project/scenario-lab.ts");
const {buildChoiceState,authorizePathsFromProjectChoice}=require("../lib/project/choice.ts");
const hardenedChoice=require("../lib/engine/scenario-lab-v1.ts");
const pathsBoundary=require("../lib/engine/choice-paths-boundary.ts");
const reading=buildProjectEngineReading(calculateVehicleProject({targetValue:80000,currentResources:20000,monthlyAmount:1500,horizon:{mode:"MONTHS",months:36}}));
const scenario=buildScenarioLab(reading);
assert.equal(scenario.observations.resourcesAtHorizon,74000);
assert.equal(scenario.observations.referenceDifference,-6000);
assert.deepEqual(scenario.choices,{pathsRequested:false,selectedPath:null,selectedProduct:null,selectedPartner:null,recommendation:null});
const choice=buildChoiceState(scenario);
assert.equal(choice.message,"O próximo passo é seu.");
assert.deepEqual(choice.actions,["Quero entender caminhos possíveis","Já tenho um caminho em mente"]);
assert.equal(choice.selectedPath,null); assert.equal(choice.recommendation,null);
const authorizedPathsChoice=authorizePathsFromProjectChoice(choice);
assert.equal(hardenedChoice.isAuthorizedChoiceState(authorizedPathsChoice),true);
const pathsIntent=pathsBoundary.emitChoicePathsIntent(authorizedPathsChoice);
assert.equal(pathsBoundary.isChoicePathsIntent(pathsIntent),true);
assert.throws(()=>authorizePathsFromProjectChoice({...choice,selectedPath:"CONSORTIUM"}),/PROJECT_CHOICE_AUTHORITY_BREACH/);
assert.throws(()=>authorizePathsFromProjectChoice({...choice,message:"x"}),/PROJECT_CHOICE_NOT_AUTHORIZED/);
assert.throws(()=>buildScenarioLab({...reading,authority:{...reading.authority,selectedPath:"CONSORTIUM"}}),/SCENARIO_AUTHORITY_BREACH/);
assert.throws(()=>buildChoiceState({...scenario,choices:{...scenario.choices,pathsRequested:true}}),/INVALID_CHOICE_SOURCE/);
assert.throws(()=>buildChoiceState({...scenario,choices:{...scenario.choices,recommendation:"x"}}),/CHOICE_AUTHORITY_BREACH/);
assert.throws(()=>buildScenarioLab(null),/INVALID_SCENARIO_SOURCE/);
assert.throws(()=>buildScenarioLab({...reading,engineVersion:"9.9.9"}),/INVALID_SCENARIO_SOURCE/);
assert.throws(()=>buildChoiceState(null),/INVALID_CHOICE_SOURCE/);
assert.throws(()=>buildChoiceState({...scenario,version:"9.9.9"}),/INVALID_CHOICE_SOURCE/);
console.log("scenario-choice-v1: PASS");
